import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const out = 'docs/ui-workflow-step1';
const categories = { File:'Header / File', Edit:'Selection / Edit', Arrange:'Cabinets / Arrange', Drafting:'Engineering / Drafting', Cabinets:'Cabinets / Library', View:'Canvas / View', Tools:'Header / Tools', Export:'Engineering / Export', Review:'Review / Production' };
const commandFiles = ['src/hooks/useAppCommandItems.ts', 'src/hooks/commandItems/draftingCabinetCommands.ts'];
const commands = [], storage = [], handlers = [];
const text = node => node?.getText() ?? '';
function destination(file) {
  if (/Present|proposal|Quote|Review|Handoff/.test(file)) return 'Review / Present / engineering handoff';
  if (/Material|Finish|SurfacePaint/.test(file)) return 'Materials / selection inspector';
  if (/Scene|ModelView|Render|Camera/.test(file)) return 'Canvas / View settings / Render Studio';
  if (/Room|Wall|Opening|Underlay|Plan|Build/.test(file)) return 'Room / contextual inspector';
  if (/Cabinet|Run|Catalog|Library/.test(file)) return 'Cabinets / contextual inspector / Library';
  return 'Existing shell or engineering surface (retain until explicitly relocated)';
}
function walk(dir) { return fs.readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(path.join(dir,e.name)) : [path.join(dir,e.name)]); }
for (const file of walk('src').filter(f => /\.tsx?$/.test(f) && !/\.test\./.test(f)).sort()) {
  const source=ts.createSourceFile(file,fs.readFileSync(file,'utf8'),ts.ScriptTarget.Latest,true,file.endsWith('tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS);
  function visit(node) {
    const line=source.getLineAndCharacterOfPosition(node.getStart()).line+1;
    if(commandFiles.includes(file)&&ts.isObjectLiteralExpression(node)) {
      const props=Object.fromEntries(node.properties.filter(ts.isPropertyAssignment).map(p=>[text(p.name),p.initializer]));
      if(props.id&&props.action){const category=props.category?.text; if(!categories[category]) throw Error('Unmapped command category '+category);commands.push({id:props.id.text,label:text(props.label),handler:text(props.action),shortcut:text(props.shortcut),source:file,line,destination:categories[category]});}
    }
    if(ts.isVariableDeclaration(node)&& /(?:STORAGE_KEY|SESSION_KEY|THEME_KEY)$/.test(text(node.name)) && node.initializer && ts.isStringLiteral(node.initializer)) storage.push({name:text(node.name),key:node.initializer.text,source:file,line});
    if(ts.isJsxAttribute(node)&&/^on[A-Z]/.test(text(node.name))) handlers.push({source:file,line,event:text(node.name),handler:text(node.initializer),destination:destination(file)});
    ts.forEachChild(node,visit);
  }
  visit(source);
}
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'source-inventory.json'),JSON.stringify({scope:'Static inventory: explicit command palette entries, literal storage keys, and JSX event bindings. Handler destinations are routing buckets, not proof of runtime reachability. Dynamic dispatch is documented in README.md.',commands,storage,handlers},null,2)+'\n');
const clean=s=>s.replaceAll('|','\\|').replaceAll('\n',' ');
fs.writeFileSync(path.join(out,'COMMANDS.md'),'# Command palette preservation inventory\n\nGenerated by `node scripts/ui-workflow-inventory.mjs`. Destinations are proposed; existing handlers remain authoritative.\n\n| ID | Current handler | Current entry point | Proposed destination |\n| --- | --- | --- | --- |\n'+commands.map(c=>`| ${c.id} | \`${clean(c.handler)}\` | [${path.basename(c.source)}:${c.line}](../../${c.source}#L${c.line}) | ${c.destination} |`).join('\n')+'\n');
console.log(JSON.stringify({commands:commands.length,storageKeys:storage.length,jsxBindings:handlers.length}));
